import { useState } from 'react';
import { AlertTriangle, FileText, Table2 } from 'lucide-react';
import { cn } from '~/lib/utils';
import type {
  DatasetPreview,
  DatasetSchema,
} from '~/features/my-datasets/types';

/**
 * Column order: the file's schema when known (stored JSON objects don't keep
 * key order — Postgres JSONB reorders them), then any extra keys in the rows.
 */
function columnsOf(rows: Record<string, unknown>[], schemaColumns: string[]) {
  const present = new Set<string>();
  for (const row of rows) for (const key of Object.keys(row)) present.add(key);
  const ordered = schemaColumns.filter((name) => present.has(name));
  return [...ordered, ...[...present].filter((key) => !ordered.includes(key))];
}

const display = (value: unknown) =>
  value === null || value === undefined
    ? ''
    : typeof value === 'object'
      ? JSON.stringify(value)
      : String(value);

/**
 * Sample rows per file from the dataset's latest version, as generated by the
 * backend preview task (first ~50 rows of each previewable file).
 */
export function DatasetDataPreview({
  preview,
  schema,
  emptyHint = 'A preview appears once uploaded files have been processed.',
}: Readonly<{
  preview?: DatasetPreview | null;
  schema?: DatasetSchema | null;
  emptyHint?: string;
}>) {
  const entries = preview?.preview_rows ?? [];
  const [fileIndex, setFileIndex] = useState(0);
  const entry = entries[Math.min(fileIndex, entries.length - 1)];

  if (!entry)
    return (
      <div className="rounded-md border border-dashed py-12 text-center text-muted-foreground">
        <Table2 className="mx-auto mb-3 h-8 w-8" />
        <p className="text-sm font-medium">No preview yet</p>
        <p className="mt-1 text-xs">{emptyHint}</p>
      </div>
    );

  const rows = entry.rows ?? [];
  const schemaFile = Array.isArray(schema?.schema_json)
    ? schema.schema_json.find((file) => file.file === entry.file)
    : undefined;
  const columns = columnsOf(
    rows,
    (schemaFile?.columns ?? []).map((column) => column.name)
  );
  const numeric = new Set(
    columns.filter((column) =>
      rows.some((row) => typeof row[column] === 'number')
    )
  );

  return (
    <div className="space-y-3">
      {entries.length > 1 && (
        <div
          role="tablist"
          aria-label="Preview file"
          className="scrollbar-hide flex gap-1 overflow-x-auto"
        >
          {entries.map((item, index) => (
            <button
              key={item.file}
              type="button"
              role="tab"
              aria-selected={item === entry}
              onClick={() => setFileIndex(index)}
              className={cn(
                'flex shrink-0 items-center gap-1.5 rounded-md border px-2.5 py-1 text-xs transition',
                item === entry
                  ? 'border-primary bg-primary/5 text-primary'
                  : 'text-muted-foreground hover:text-foreground'
              )}
            >
              <FileText className="h-3.5 w-3.5" />
              {item.file}
            </button>
          ))}
        </div>
      )}

      {entry.error ? (
        <div className="flex items-start gap-2 rounded-lg border border-destructive/20 bg-destructive/5 px-4 py-3 text-sm text-destructive">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" />
          <span>
            Could not preview <strong>{entry.file}</strong>: {entry.error}
          </span>
        </div>
      ) : (
        <>
          <div className="scrollbar-thin max-h-[28rem] overflow-auto rounded-lg border">
            <table className="w-max min-w-full text-sm">
              <thead className="sticky top-0 z-10 bg-muted/90 backdrop-blur">
                <tr className="text-xs text-muted-foreground">
                  <th className="px-3 py-2 text-left font-medium">#</th>
                  {columns.map((column) => (
                    <th
                      key={column}
                      className={cn(
                        'px-3 py-2 font-medium whitespace-nowrap',
                        numeric.has(column) ? 'text-right' : 'text-left'
                      )}
                    >
                      {column}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {rows.map((row, index) => (
                  <tr
                    key={index}
                    className="border-t transition-colors hover:bg-muted/40"
                  >
                    <td className="px-3 py-2 text-xs text-muted-foreground tabular-nums">
                      {index + 1}
                    </td>
                    {columns.map((column) => {
                      const value = row[column];
                      const text = display(value);
                      return (
                        <td
                          key={column}
                          title={text}
                          className={cn(
                            'max-w-80 truncate px-3 py-2 whitespace-nowrap',
                            numeric.has(column) && 'text-right tabular-nums'
                          )}
                        >
                          {text}
                        </td>
                      );
                    })}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="text-center text-xs text-muted-foreground">
            Showing the first {rows.length} rows of {entry.file} ·{' '}
            {columns.length} columns
          </p>
        </>
      )}
    </div>
  );
}
